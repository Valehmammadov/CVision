"use client";

import { useEffect, useRef, useState } from "react";
import { AnimatePresence, motion } from "framer-motion";
import { CalendarCheck, Check, CheckCircle2, ChevronDown, Loader2, Sparkles, Undo2, X, XCircle } from "lucide-react";
import { toast } from "sonner";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { DecisionChip, ScoreRing } from "@/components/CandidateCard";
import { SkillVerification } from "@/components/SkillVerification";
import { MethodBadge } from "@/components/MethodBadge";
import { cn } from "@/lib/utils";
import {
  CATEGORY_LABELS,
  CATEGORY_ORDER,
  CATEGORY_WEIGHTS,
  DISCLAIMER,
  RECOMMENDATION_THRESHOLDS,
} from "@/config/screening";
import { fitStyles, type Candidate, type Decision, type VerificationResult } from "@/data/candidates";

/** Category labels for a candidate (the third category depends on the job). */
function labelsFor(c: Candidate) {
  return CATEGORY_ORDER.map((key) => ({
    key,
    label: c.categoryLabels?.[key] ?? CATEGORY_LABELS[key],
    weight: Math.round(CATEGORY_WEIGHTS[key] * 100),
  }));
}

const METHOD_LIMITATIONS: Record<Candidate["method"], string> = {
  demo: "Fictional demonstration profile. Scores and metrics are hand-picked demo values, not results from an analyzed CV.",
  "rule-based":
    "Rule-based scoring looks for keyword evidence and simple patterns such as dated roles. It can't judge the depth or quality of work, may miss unusual wording or layouts, and can over-reward keyword-heavy CVs.",
  ai: "AI-assisted scores are generated by Gemini from the extracted CV text and validated by CVisionAI. AI models can misread context or make mistakes, so verify key claims in the CV.",
};

interface Props {
  candidate: Candidate | null;
  onClose: () => void;
  decision?: Decision;
  onDecision: (id: string, d: Decision | null) => void;
  verification?: VerificationResult;
  onVerified: (id: string, v: VerificationResult) => void;
}

export function CandidateDetailModal({ candidate, onClose, decision, onDecision, verification, onVerified }: Props) {
  const closeRef = useRef<HTMLButtonElement>(null);

  // Escape to close, lock background scroll, restore focus on close.
  useEffect(() => {
    if (!candidate) return;
    const previouslyFocused = document.activeElement as HTMLElement | null;
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    const prevOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    const t = setTimeout(() => closeRef.current?.focus(), 50);
    return () => {
      clearTimeout(t);
      window.removeEventListener("keydown", onKey);
      document.body.style.overflow = prevOverflow;
      previouslyFocused?.focus?.();
    };
  }, [candidate, onClose]);

  return (
    <AnimatePresence>
      {candidate && (
        <div className="fixed inset-0 z-50" key="slide-over">
          <motion.div
            className="absolute inset-0 bg-[#0b1f3a]/40 backdrop-blur-sm"
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            onClick={onClose}
            aria-hidden="true"
          />
          <motion.aside
            role="dialog"
            aria-modal="true"
            aria-labelledby="candidate-detail-title"
            className="absolute inset-y-0 right-0 flex w-full max-w-xl flex-col bg-surface shadow-2xl"
            initial={{ x: "100%" }}
            animate={{ x: 0 }}
            exit={{ x: "100%" }}
            transition={{ type: "spring", damping: 30, stiffness: 280 }}
          >
            <Detail
              key={candidate.id}
              candidate={candidate}
              onClose={onClose}
              closeRef={closeRef}
              decision={decision}
              onDecision={onDecision}
              verification={verification}
              onVerified={onVerified}
            />
          </motion.aside>
        </div>
      )}
    </AnimatePresence>
  );
}

function metricColor(v: number) {
  if (v >= 80) return "bg-emerald-500";
  if (v >= 60) return "bg-amber-500";
  return "bg-red-500";
}

function Detail({
  candidate,
  onClose,
  closeRef,
  decision,
  onDecision,
  verification,
  onVerified,
}: {
  candidate: Candidate;
  onClose: () => void;
  closeRef: React.RefObject<HTMLButtonElement | null>;
  decision?: Decision;
  onDecision: (id: string, d: Decision | null) => void;
  verification?: VerificationResult;
  onVerified: (id: string, v: VerificationResult) => void;
}) {
  const style = fitStyles[candidate.fit];
  const [busy, setBusy] = useState<Decision | null>(null);
  const [confirmReject, setConfirmReject] = useState(false);

  // The "Confirm rejection" state expires after a few seconds.
  useEffect(() => {
    if (!confirmReject) return;
    const t = setTimeout(() => setConfirmReject(false), 4000);
    return () => clearTimeout(t);
  }, [confirmReject]);

  // Demo only: no emails are actually sent.
  function scheduleInterview() {
    if (busy) return;
    setBusy("invited");
    setTimeout(() => {
      setBusy(null);
      onDecision(candidate.id, "invited");
      toast.success("Interview invitation sent to candidate via email!");
    }, 700);
  }

  function rejectCandidate() {
    if (busy) return;
    if (!confirmReject) {
      setConfirmReject(true);
      return;
    }
    setConfirmReject(false);
    setBusy("rejected");
    setTimeout(() => {
      setBusy(null);
      onDecision(candidate.id, "rejected");
      toast("Rejection notice sent to candidate via email.", {
        icon: <XCircle className="h-4 w-4 text-slate-500" />,
        action: { label: "Undo", onClick: () => onDecision(candidate.id, null) },
      });
    }, 600);
  }

  return (
    <>
      {/* Header */}
      <div className="flex items-start justify-between gap-4 border-b border-slate-200 p-5 sm:p-6">
        <div className="flex min-w-0 items-center gap-4">
          <ScoreRing score={candidate.score} hex={style.hex} size={80} />
          <div className="min-w-0">
            <p className="text-xs font-medium uppercase tracking-wide text-slate-400">Candidate profile</p>
            <h3 id="candidate-detail-title" className="truncate text-xl font-bold text-navy">
              {candidate.name}
            </h3>
            <p className="text-sm text-slate-500">
              {candidate.targetRole}
              {candidate.screeningProfile && (
                <span className="text-slate-400"> · screened as {candidate.screeningProfile}</span>
              )}
            </p>
            <div className="mt-1.5 flex flex-wrap items-center gap-1.5">
              <MethodBadge method={candidate.method} />
              <DecisionChip decision={decision} />
              {candidate.fileName && (
                <span className="max-w-[12rem] truncate text-xs text-slate-400" title={candidate.fileName}>
                  {candidate.fileName}
                </span>
              )}
            </div>
          </div>
        </div>
        <button
          ref={closeRef}
          aria-label="Close candidate details"
          onClick={onClose}
          className="cursor-pointer rounded-lg p-1.5 text-slate-400 transition-colors hover:bg-slate-100 hover:text-slate-700 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-blue-500"
        >
          <X className="h-5 w-5" />
        </button>
      </div>

      {/* Body */}
      <div className="flex-1 space-y-6 overflow-y-auto p-5 sm:p-6">
        <div className="grid grid-cols-3 gap-2 sm:gap-3">
          <InfoTile label="Match score" value={`${candidate.score}%`} />
          <InfoTile label="Match quality" value={candidate.label} className={style.text} />
          <InfoTile label="Verdict" value={candidate.verdict} className={style.text} />
        </div>

        <section>
          <div className="mb-3 flex items-baseline justify-between">
            <h4 className="text-sm font-semibold text-navy">Evaluation metrics</h4>
            <span className="text-xs text-slate-400">
              {candidate.method === "demo" ? "Illustrative demo values" : "Category scores · weight"}
            </span>
          </div>
          <div className="space-y-3.5">
            {labelsFor(candidate).map(({ key, label, weight }, i) => {
              const v = candidate.metrics[key];
              return (
                <div key={key}>
                  <div className="mb-1 flex justify-between text-sm">
                    <span className="text-slate-600">
                      {label} <span className="text-xs text-slate-400">· {weight}%</span>
                    </span>
                    <span className="font-semibold text-navy">{v}%</span>
                  </div>
                  <div className="h-2 overflow-hidden rounded-full bg-slate-100">
                    <motion.div
                      className={cn("h-full rounded-full", metricColor(v))}
                      initial={{ width: 0 }}
                      animate={{ width: `${v}%` }}
                      transition={{ delay: 0.15 + i * 0.08, duration: 0.7, ease: "easeOut" }}
                    />
                  </div>
                </div>
              );
            })}
          </div>
        </section>

        <section>
          <h4 className="mb-2 text-sm font-semibold text-navy">Key strengths</h4>
          <div className="flex flex-wrap gap-1.5">
            {candidate.strengths.map((s) => (
              <Badge key={s} variant="strength">
                <Check className="h-3 w-3" />
                {s}
              </Badge>
            ))}
          </div>
        </section>

        <section>
          <h4 className="mb-2 text-sm font-semibold text-navy">Skill gaps</h4>
          <div className="flex flex-wrap gap-1.5">
            {candidate.gaps.length === 0 && (
              <span className="text-xs text-slate-400">No significant gaps found</span>
            )}
            {candidate.gaps.map((g) => (
              <Badge key={g} variant="gap">
                <X className="h-3 w-3" />
                {g}
              </Badge>
            ))}
          </div>
        </section>

        <section>
          <h4 className="mb-2 flex items-center gap-1.5 text-sm font-semibold text-navy">
            <Sparkles className="h-4 w-4 text-blue-600" />
            Evaluation summary
          </h4>
          <p className="text-sm leading-relaxed text-slate-600">{candidate.evaluation}</p>
        </section>

        <SkillVerification candidate={candidate} result={verification} onResult={(v) => onVerified(candidate.id, v)} />

        <ScoreBreakdown candidate={candidate} />

        <section className={cn("rounded-xl border p-4", style.bg)}>
          <p className="text-xs font-medium uppercase tracking-wide text-slate-500">Final recommendation</p>
          <p className={cn("mt-0.5 text-lg font-bold", style.text)}>{candidate.verdict}</p>
        </section>

        <div className="space-y-2 rounded-lg bg-slate-50 p-3 text-xs leading-relaxed text-slate-500">
          {candidate.methodNote && (
            <p className="font-medium text-slate-600" data-testid="method-note-detail">
              {candidate.methodNote}
            </p>
          )}
          <p>{METHOD_LIMITATIONS[candidate.method]}</p>
          <p>{DISCLAIMER}</p>
        </div>
      </div>

      {/* Footer — demo actions only, no emails are sent */}
      <div className="grid grid-cols-2 gap-2 border-t border-slate-200 bg-surface p-4 sm:flex sm:p-5">
        <Button variant="outline" className="order-3 col-span-2 sm:order-none sm:w-24" onClick={onClose}>
          Close
        </Button>
        {decision === "rejected" ? (
          <Button
            variant="outline"
            size="lg"
            className="sm:w-44"
            onClick={() => onDecision(candidate.id, null)}
            disabled={!!busy}
          >
            <Undo2 className="h-4 w-4" />
            Undo rejection
          </Button>
        ) : (
          <Button
            variant="outline"
            size="lg"
            className={cn(
              "sm:w-44",
              confirmReject
                ? "border-red-600 bg-red-600 text-white hover:border-red-700 hover:bg-red-700 dark:hover:border-red-500 dark:hover:bg-red-500"
                : "border-red-200 text-red-600 hover:border-red-300 hover:bg-red-50"
            )}
            onClick={rejectCandidate}
            disabled={!!busy}
            aria-busy={busy === "rejected"}
          >
            {busy === "rejected" ? (
              <>
                <Loader2 className="h-4 w-4 animate-spin" />
                Rejecting…
              </>
            ) : confirmReject ? (
              <>
                <XCircle className="h-4 w-4" />
                Confirm rejection
              </>
            ) : (
              <>
                <XCircle className="h-4 w-4" />
                Reject
              </>
            )}
          </Button>
        )}
        <Button
          size="lg"
          className="hover:-translate-y-0.5 hover:shadow-lg active:translate-y-0 active:scale-[0.99] sm:flex-1"
          onClick={scheduleInterview}
          disabled={!!busy}
          aria-busy={busy === "invited"}
        >
          {busy === "invited" ? (
            <>
              <Loader2 className="h-5 w-5 animate-spin" />
              Sending…
            </>
          ) : decision === "invited" ? (
            <>
              <CheckCircle2 className="h-5 w-5" />
              Invited · Resend
            </>
          ) : (
            <>
              <CalendarCheck className="h-5 w-5" />
              Schedule Interview
            </>
          )}
        </Button>
      </div>
    </>
  );
}

function ScoreBreakdown({ candidate }: { candidate: Candidate }) {
  const [open, setOpen] = useState(false);
  const formula = labelsFor(candidate)
    .map(({ key, weight }) => `${candidate.metrics[key]} × ${(weight / 100).toFixed(2)}`)
    .join(" + ");

  return (
    <section className="rounded-xl border border-slate-200">
      <button
        type="button"
        onClick={() => setOpen((o) => !o)}
        aria-expanded={open}
        className="flex w-full cursor-pointer items-center justify-between gap-2 rounded-xl px-4 py-3 text-left text-sm font-semibold text-navy transition-colors hover:bg-slate-50"
      >
        How this score was calculated
        <ChevronDown className={cn("h-4 w-4 text-slate-400 transition-transform", open && "rotate-180")} />
      </button>
      <AnimatePresence initial={false}>
        {open && (
          <motion.div
            initial={{ height: 0, opacity: 0 }}
            animate={{ height: "auto", opacity: 1 }}
            exit={{ height: 0, opacity: 0 }}
            className="overflow-hidden"
          >
            <div className="space-y-4 border-t border-slate-200 px-4 py-3 text-xs text-slate-600">
              <p className="rounded-lg bg-slate-50 p-2 font-mono text-[11px] leading-relaxed text-slate-700">
                Overall = {formula} ≈ <span className="font-bold">{candidate.score}%</span>
              </p>
              {candidate.evidence ? (
                labelsFor(candidate).map(({ key, label }) => (
                  <div key={key}>
                    <p className="mb-1 font-semibold text-slate-700">
                      {label} — {candidate.metrics[key]}%
                    </p>
                    <ul className="list-disc space-y-0.5 pl-4">
                      {(candidate.evidence?.[key] ?? []).map((line, i) => (
                        <li key={i}>{line}</li>
                      ))}
                    </ul>
                  </div>
                ))
              ) : (
                <p>Demo profile — no CV evidence is available for this candidate.</p>
              )}
              <p className="text-slate-400">
                Recommendation thresholds: {RECOMMENDATION_THRESHOLDS.interview}%+ Recommend Interview ·{" "}
                {RECOMMENDATION_THRESHOLDS.hold}–{RECOMMENDATION_THRESHOLDS.interview - 1}% Hold · below{" "}
                {RECOMMENDATION_THRESHOLDS.hold}% Reject.
              </p>
            </div>
          </motion.div>
        )}
      </AnimatePresence>
    </section>
  );
}

function InfoTile({ label, value, className }: { label: string; value: string; className?: string }) {
  return (
    <div className="rounded-xl border border-slate-200 bg-slate-50/60 p-3">
      <p className="text-[11px] font-medium uppercase tracking-wide text-slate-400">{label}</p>
      <p className={cn("mt-0.5 text-sm font-bold leading-tight text-navy sm:text-base", className)}>
        {value}
      </p>
    </div>
  );
}
