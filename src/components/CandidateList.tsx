"use client";

import { useMemo, useState } from "react";
import { AnimatePresence, motion } from "framer-motion";
import { SearchX } from "lucide-react";
import { Info } from "lucide-react";
import type { Candidate, Decision, ResultsMethod, VerificationResult } from "@/data/candidates";
import { DISCLAIMER } from "@/config/screening";
import { MethodBadge } from "@/components/MethodBadge";
import { CandidateCard } from "@/components/CandidateCard";
import { Button } from "@/components/ui/button";
import {
  ScoreFilter,
  matchesScoreFilter,
  scoreFilterOptions,
  type ScoreFilterValue,
} from "@/components/ScoreFilter";

interface Props {
  candidates: Candidate[];
  method: ResultsMethod;
  /** The job title/description was edited after these results were produced. */
  jobChanged?: boolean;
  decisions?: Record<string, Decision>;
  verifications?: Record<string, VerificationResult>;
  onSelect: (c: Candidate) => void;
}

const METHOD_NOTE: Record<ResultsMethod, string> = {
  demo: "Showing fictional sample candidates. Upload CVs and click Analyze to screen real applicants.",
  "rule-based":
    "Scored by CVisionAI's transparent rule-based engine (weighted keyword and experience evidence).",
  ai: "Category scores and summaries generated by Gemini from the CV text; overall score uses CVisionAI's weights.",
  mixed:
    "Most candidates were evaluated by Gemini; some fell back to the rule-based engine (see each candidate's details).",
};

export function CandidateList({
  candidates,
  method,
  jobChanged,
  decisions = {},
  verifications = {},
  onSelect,
}: Props) {
  const [filter, setFilter] = useState<ScoreFilterValue>("all");

  const visible = useMemo(
    () => candidates.filter((c) => matchesScoreFilter(c.score, filter)),
    [candidates, filter]
  );
  const filterLabel = scoreFilterOptions.find((o) => o.value === filter)!.label;

  return (
    <section aria-labelledby="candidates-heading">
      <div className="mb-3 flex flex-col gap-3 sm:flex-row sm:items-end sm:justify-between">
        <div>
          <div className="flex flex-wrap items-center gap-2">
            <h2 id="candidates-heading" className="text-lg font-semibold text-navy">
              Candidates
            </h2>
            <MethodBadge method={method} />
          </div>
          <p className="mt-0.5 text-sm text-slate-500" aria-live="polite" data-testid="visible-count">
            Showing <span className="font-semibold text-navy">{visible.length}</span> of{" "}
            {candidates.length} candidates
          </p>
        </div>
        <div>
          <p className="mb-1 text-xs font-medium text-slate-500">Filter by Match Score</p>
          <ScoreFilter value={filter} onChange={setFilter} />
        </div>
      </div>

      <p className="mb-4 flex items-start gap-1.5 text-xs text-slate-500" data-testid="method-note">
        <Info className="mt-px h-3.5 w-3.5 shrink-0 text-slate-400" />
        <span>
          {METHOD_NOTE[method]}
          {method !== "demo" && candidates[0]?.screeningProfile && (
            <>
              {" "}
              Role profile: <span className="font-medium text-slate-600">{candidates[0].screeningProfile}</span>.
            </>
          )}
        </span>
      </p>
      {jobChanged && (
        <p
          className="mb-4 flex items-start gap-1.5 rounded-lg border border-amber-200 bg-amber-50 px-3 py-2 text-xs text-amber-800"
          role="status"
          data-testid="job-changed"
        >
          <Info className="mt-px h-3.5 w-3.5 shrink-0" />
          The job title or description changed since this analysis. Click Analyze to re-screen the CVs for the
          updated role.
        </p>
      )}

      <div className="space-y-4">
        <AnimatePresence mode="popLayout" initial={false}>
          {visible.map((c, i) => (
            <motion.div
              key={c.id}
              layout
              initial={{ opacity: 0, scale: 0.98 }}
              animate={{ opacity: 1, scale: 1 }}
              exit={{ opacity: 0, scale: 0.98 }}
              transition={{ duration: 0.2 }}
            >
              <CandidateCard
                candidate={c}
                index={i}
                rank={candidates.indexOf(c) + 1}
                showRank={method !== "demo"}
                decision={decisions[c.id]}
                verification={verifications[c.id]}
                onSelect={onSelect}
              />
            </motion.div>
          ))}
        </AnimatePresence>

        {visible.length === 0 && (
          <motion.div
            initial={{ opacity: 0, y: 8 }}
            animate={{ opacity: 1, y: 0 }}
            className="flex flex-col items-center rounded-2xl border border-dashed border-slate-300 bg-surface px-6 py-12 text-center"
          >
            <div className="mb-3 flex h-12 w-12 items-center justify-center rounded-full bg-slate-100 text-slate-400">
              <SearchX className="h-6 w-6" />
            </div>
            <p className="font-semibold text-navy">No candidates in the {filterLabel} range</p>
            <p className="mb-4 mt-1 text-sm text-slate-500">
              Try a different match score range to see more candidates.
            </p>
            <Button variant="outline" size="sm" onClick={() => setFilter("all")}>
              Show all candidates
            </Button>
          </motion.div>
        )}
      </div>

      <p
        className="mt-5 rounded-xl border border-slate-200 bg-surface px-4 py-3 text-xs leading-relaxed text-slate-500"
        data-testid="disclaimer"
      >
        <span className="font-semibold text-slate-600">Disclaimer: </span>
        {DISCLAIMER}
      </p>
    </section>
  );
}
